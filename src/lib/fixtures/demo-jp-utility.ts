/**
 * Demo 2 - Japanese utility bill, in two steps.
 *
 * Step 1 is the paper 払込票 that arrives in the post: an amount, a due date,
 * and a barcode at the bottom. Step 2 is what the user sees *after* scanning
 * that barcode with a phone payment app - and that screen is a document too.
 * It is the moment the paper hands the reader over to an interface nobody
 * explained to them, which is exactly where help stops being available.
 *
 * SAFETY: both pages are invented. ○○ガス and ○○ペイ are placeholder names,
 * not a real utility and not a real payment service; every digit is a 0
 * pattern; the barcode is a fixed decorative pattern that encodes nothing. The
 * app screen is drawn from scratch rather than copied from any product's UI.
 *
 * As with the Korean notice, one figure is deliberately missing: the slip says
 * a late charge exists but never prints its amount.
 *
 * WHAT THE ANALYSIS EXPLAINS. This track's reader is a Japanese pensioner, in
 * Japan, holding a bill in their own language. They do not need "8,181円 is
 * the amount" - they have paid gas bills for decades, and saying it out loud
 * would be insulting. What is genuinely new is the phone: that a barcode app
 * pays from a balance topped up in advance rather than from a bank account,
 * that 支払い予約 schedules a payment without making one, that the app cannot
 * undo it afterwards, and that paying the same slip twice - once at the shop,
 * once in the app - is possible and nothing stops you.
 */
